"""Lowest natural frequencies of the housing with the contact patch blocked, one per impact case.

Same mesh, materials and N_CONTACT group as the June shock files (read from them); the patch nodes are
fixed in translation, as in the transient runs. These frequencies set the time scale of the response once
the 2.524 ms pulse has ended (pulse duration / period ratio).

usage: python make_cases_modes_bc.py <outdir> [case ...]
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "LIVRABLE_RAPPORT_CHOC_CARTER_CYLINDRIQUE_V1" / "04_CODE_ASTER"
MESH = HERE / "carter_socle_xy_z_netgen.med"
RUN_ASTER = r"D:\Code_Aster\v2025\17.4\bin\run_aster.bat"
CASES = ["cyl_ymin", "cyl_ymax", "cyl_oblique_ymin_z"]


def make(case, outdir):
    src = (SRC / f"carter_choc_{case}.comm").read_text(encoding="utf-8")
    head = src[:src.index("# Impulsion inertielle simplifiee")] if "# Impulsion inertielle simplifiee" in src \
        else src[:src.index("CHOC_DYN = AFFE_CHAR_MECA(")]
    assert "BC_CONTACT = AFFE_CHAR_MECA(" in head
    tail = """
ASSEMBLAGE(MODELE=MODELE, CHAM_MATER=CHMAT, CHARGE=BC_CONTACT, NUME_DDL=CO('NUMEDDL'),
           MATR_ASSE=(_F(MATRICE=CO('RIGI'), OPTION='RIGI_MECA'), _F(MATRICE=CO('MASS'), OPTION='MASS_MECA')))
MODES = CALC_MODES(MATR_RIGI=RIGI, MATR_MASS=MASS, OPTION='PLUS_PETITE', TYPE_RESU='DYNAMIQUE',
                   CALC_FREQ=_F(NMAX_FREQ=6), VERI_MODE=_F(STOP_ERREUR='NON'))
TF = RECU_TABLE(CO=MODES, NOM_PARA=('NUME_MODE', 'FREQ'))
IMPR_TABLE(TABLE=TF, UNITE=8)
FIN()
"""
    out = Path(outdir).resolve(); out.mkdir(parents=True, exist_ok=True)
    comm = out / f"{case}.comm"
    comm.write_text(head.replace("DEBUT(LANG='FR')", f"DEBUT(LANG='FR')\n# Generated by make_cases_modes_bc.py from carter_choc_{case}.comm") + tail, encoding="utf-8")
    export = out / f"{case}.export"
    export.write_text("\n".join([
        "P actions make_etude", "P debug nodebug", "P memjob 12582912", "P memory_limit 12288.0",
        "P mode interactif", "P mpi_nbcpu 1", "P mpi_nbnoeud 1", "P ncpus 2", f"P nomjob modes_{case}",
        "P server localhost", "P time_limit 36000.0", "P tpsjob 600", "P version 17.4",
        "A memjeveux 4096.0", "A tpmax 36000.0",
        f"F comm {comm} D 1", f"F libr {MESH} D 20",
        f"F resu {out / (case + '_freq.txt')} R 8", f"F mess {out / ('message_' + case + '.txt')} R 6", ""]),
        encoding="utf-8")
    (out / f"run_{case}.bat").write_text(f'@ECHO OFF\r\nCALL "{RUN_ASTER}" "{export}"\r\n', encoding="utf-8")
    return comm


if __name__ == "__main__":
    for c in (sys.argv[2:] or CASES):
        print(make(c, sys.argv[1]))
