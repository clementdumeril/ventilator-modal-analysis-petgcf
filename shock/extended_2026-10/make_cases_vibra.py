"""Linear transient (DYNA_VIBRA, physical basis) version of the June shroud-impact runs.

The June runs used DYNA_NON_LINE with RELATION='ELAS' and small strains: a linear problem solved with a
non-linear solver, which recomputes internal forces over all 312,777 elements at every step. DYNA_VIBRA
solves the same equations, M u'' + K u = f(t) with the contact nodes blocked, with the same Newmark
average-acceleration scheme (beta = 1/4, gamma = 1/2) and dt = 1e-4 s, factorising once. Stresses
(SIEF_ELGA -> SIEQ_ELGA) are computed afterwards at the archived instants only.
Everything else (mesh, groups, materials, contact patch, pulse, load direction) is read from the June
.comm file of each case, so the two inputs cannot drift apart. Equivalence is checked in
01_VALIDATION_2p5ms against the June results.

usage: python make_cases_vibra.py <outdir> <t_end> <dt_arch> [case ...]
(input paths: CHOC_SRC, CHOC_MESH, CHOC_RUN_ASTER, see below)
(time step 1e-4 s by default; set CHOC_DT=5e-5 for the time-step check)
Optional quadratic elements: CHOC_QUAD=1 converts the mesh to TETRA10 after the element groups are built (same
mass zones), re-creates the contact node group on the quadratic mesh (mid-side nodes included) and writes only
DEPL and the VMIS component of SIEQ_ELGA.
Optional Rayleigh damping C = alpha M + beta K (material AMOR_ALPHA/AMOR_BETA, assembled with AMOR_MECA): set CHOC_ZETA (e.g. 0.02) and the two frequencies where the
damping ratio equals zeta, CHOC_FA and CHOC_FB in Hz (default 15 and 300); between them the ratio is lower.
Long TETRA10 runs: CHOC_STRESS_FROM (s) computes and writes the stresses only from that instant on, and CHOC_TMPDIR
puts the scratch directory on a disk with room for it (a 60 ms run with stresses at all 301 archived instants needs
an estimated 120 GB of scratch space).
"""
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
# Paths, overridable from the environment: the June .comm files (CHOC_SRC, default shock/code_aster/ of this
# repository), the NETGEN mesh in MED format (CHOC_MESH; not versioned, produced by src/mesh/mesh_carter_netgen.py)
# and the Code_Aster launcher (CHOC_RUN_ASTER, e.g. run_aster on Linux).
SRC = Path(os.environ.get("CHOC_SRC", HERE.parent / "code_aster"))
MESH = Path(os.environ.get("CHOC_MESH", HERE / "carter_socle_xy_z_netgen.med")).resolve()
RUN_ASTER = os.environ.get("CHOC_RUN_ASTER", r"D:\Code_Aster\v2025\17.4\bin\run_aster.bat")
CASES = ["cyl_ymin", "cyl_ymax", "cyl_oblique_ymin_z"]
# Corrected oblique case. In the June cyl_oblique_ymin_z input the plane of the fixed nodes (normal (0, 1, 1)/sqrt 2,
# through the Y- side of the shroud) is not tangent to the housing: it cuts through the shroud, the stand and the base,
# so a slice of 1091 nodes is fixed. A 45 degree fall towards Y- and down first touches the edge of the base, at the node
# that minimises y + z, (28.03, -99.17, 0). Same pulse and direction, plane through that node, 3 mm tolerance as Y-.
DERIVED = {"oblique_base_edge": ("cyl_oblique_ymin_z", {
    "POINT=(-6.31, -135.05, 164.18),": "POINT=(28.03, -99.17, 0.0),",
    "PRECISION=1.0,": "PRECISION=3.0,"})}
DT = float(os.environ.get("CHOC_DT", "1e-4"))
QUAD = os.environ.get("CHOC_QUAD", "0") == "1"
ZETA = float(os.environ.get("CHOC_ZETA", "0"))
FA, FB = float(os.environ.get("CHOC_FA", "15")), float(os.environ.get("CHOC_FB", "300"))
STRESS_FROM = float(os.environ.get("CHOC_STRESS_FROM", "0"))   # first instant (s) where stresses are computed
TMPDIR = os.environ.get("CHOC_TMPDIR", "")                       # scratch directory of the run (TEMP), if not the default


def make(case, outdir, t_end, dt_arch):
    base, edits = DERIVED.get(case, (case, {}))
    src = (SRC / f"carter_choc_{base}.comm").read_text(encoding="utf-8")
    for old, new in edits.items():
        assert src.count(old) == 1, old
        src = src.replace(old, new)
    head = src[:src.index("L_INST = DEFI_LIST_REEL(")]          # mesh .. CHOC_DYN .. PULSE, unchanged
    if QUAD:
        i = head.index("MODELE = AFFE_MODELE(")
        g0 = head.index("    CREA_GROUP_NO=(")
        g1 = head.index("\n    ),", g0)
        crea_no = head[g0:g1 + len("\n    ),")]
        conv = ("MAILQ = CREA_MAILLAGE(MAILLAGE=MAIL, LINE_QUAD=_F(TOUT='OUI'))\n"
                "MAILQ = DEFI_GROUP(\n    reuse=MAILQ,\n    MAILLAGE=MAILQ,\n"
                "    DETR_GROUP_NO=_F(NOM='N_CONTACT'),\n" + crea_no + "\n)\n\n")
        rest = head[i:].replace("MAILLAGE=MAIL,", "MAILLAGE=MAILQ,")
        assert rest.count("MAILLAGE=MAILQ,") == 2, rest.count("MAILLAGE=MAILQ,")
        head = head[:i] + conv + rest
    assert "PULSE = DEFI_FONCTION(" in head and "CHOC_DYN = AFFE_CHAR_MECA(" in head
    head = head.replace("DEBUT(LANG='FR')",
                        f"DEBUT(LANG='FR')\n# Generated by make_cases_vibra.py from {SRC.name}/carter_choc_{base}.comm{' with the contact plane of ' + case if edits else ''}:"
                        f" DYNA_VIBRA, {'TETRA10' if QUAD else 'TETRA4'}, dt={DT}, zeta={ZETA} ({FA}-{FB} Hz), t_end={t_end}, dt_arch={dt_arch}")
    damp_def, damp_kw, damp_asse = "", "", ""
    if ZETA > 0:
        # Rayleigh damping C = alpha M + beta K, built element by element from the material
        # (code_aster: AMOR_ALPHA multiplies K, AMOR_BETA multiplies M) and assembled with AMOR_MECA,
        # so the Lagrange multipliers of the fixed patch are not scaled (COMB_MATR_ASSE of the assembled
        # M and K made the initial-acceleration step fail with a floating-point exception).
        import math
        wa, wb = 2 * math.pi * FA, 2 * math.pi * FB
        alpha, beta = 2 * ZETA * wa * wb / (wa + wb), 2 * ZETA / (wa + wb)
        n_elas = head.count("        NU=0.35,\n")
        assert n_elas == 3, n_elas
        head = head.replace("        NU=0.35,\n", f"        NU=0.35,\n        AMOR_ALPHA={beta!r},\n        AMOR_BETA={alpha!r},\n")
        damp_def = f"# Rayleigh damping, zeta = {ZETA} at {FA} and {FB} Hz: alpha (mass) = {alpha:.6g} 1/s, beta (stiffness) = {beta:.6g} s\n"
        damp_asse = ", _F(MATRICE=CO('AMOR'), OPTION='AMOR_MECA')"
        damp_kw = " MATR_AMOR=AMOR,"
    sig_def, sel = "", ""
    if STRESS_FROM > 0:
        # stresses only at the archived instants from STRESS_FROM on (the stress fields of a long TETRA10 run
        # do not fit in the scratch space otherwise); displacements stay at every archived instant
        sig_def = f"L_SIG = DEFI_LIST_REEL(DEBUT={STRESS_FROM!r}, INTERVALLE=_F(JUSQU_A={t_end!r}, PAS={dt_arch!r}))\n"
        sel = f" LIST_INST=L_SIG, CRITERE='ABSOLU', PRECISION={DT / 4!r},"
    impr = ("IMPR_RESU(FORMAT='MED', UNITE=80, RESU=(_F(RESULTAT=RESU, NOM_CHAM='DEPL'),\n"
            f"                                        _F(RESULTAT=RESU,{sel} NOM_CHAM='SIEQ_ELGA', NOM_CMP='VMIS')))"
            if QUAD else "IMPR_RESU(FORMAT='MED', UNITE=80, RESU=_F(RESULTAT=RESU, NOM_CHAM=('DEPL', 'SIEQ_ELGA')))")
    assert QUAD or not sel, "CHOC_STRESS_FROM is implemented for CHOC_QUAD=1 only"
    tail = f"""
L_INST = DEFI_LIST_REEL(DEBUT=0.0, INTERVALLE=_F(JUSQU_A={t_end!r}, PAS={DT!r}))

ASSEMBLAGE(
    MODELE=MODELE, CHAM_MATER=CHMAT, CHARGE=BC_CONTACT, NUME_DDL=CO('NUMEDDL'),
    MATR_ASSE=(_F(MATRICE=CO('RIGI'), OPTION='RIGI_MECA'), _F(MATRICE=CO('MASS'), OPTION='MASS_MECA'){damp_asse}),
    VECT_ASSE=(_F(VECTEUR=CO('F_CHOC'), OPTION='CHAR_MECA', CHARGE=CHOC_DYN),),
)

{damp_def}RESU = DYNA_VIBRA(
    TYPE_CALCUL='TRAN', BASE_CALCUL='PHYS',
    MODELE=MODELE, CHAM_MATER=CHMAT,
    MATR_MASS=MASS, MATR_RIGI=RIGI,{damp_kw}          # BC_CONTACT is in NUME_DDL through ASSEMBLAGE
    SCHEMA_TEMPS=_F(SCHEMA='NEWMARK', BETA=0.25, GAMMA=0.5),
    INCREMENT=_F(LIST_INST=L_INST),
    EXCIT=_F(VECT_ASSE=F_CHOC, FONC_MULT=PULSE),
    ARCHIVAGE=_F(PAS_ARCH={round(dt_arch / DT)}),     # every n steps (a list of instants failed on rounding)
    SOLVEUR=_F(METHODE='MUMPS'),
)

{sig_def}RESU = CALC_CHAMP(reuse=RESU, RESULTAT=RESU,{sel} CONTRAINTE=('SIEF_ELGA',), CRITERES=('SIEQ_ELGA',))

{impr}

FIN()
"""
    out = Path(outdir).resolve(); out.mkdir(parents=True, exist_ok=True)
    comm = out / f"{case}.comm"; comm.write_text(head + tail, encoding="utf-8")
    export = out / f"{case}.export"
    export.write_text("\n".join([
        "P actions make_etude", "P debug nodebug", "P memjob 16777216", "P memory_limit 16384.0",
        "P mode interactif", "P mpi_nbcpu 1", "P mpi_nbnoeud 1", "P ncpus 2",
        f"P nomjob {case}", "P server localhost", "P time_limit 172800.0", "P tpsjob 2880",
        "P version 17.4", "A memjeveux 4096.0", "A tpmax 172800.0",
        f"F comm {comm} D 1", f"F libr {MESH} D 20",
        f"F libr {out / (case + '.rmed')} R 80",
        f"F mess {out / ('message_' + case + '.txt')} R 6", ""]), encoding="utf-8")
    bat = out / f"run_{case}.bat"
    tmp = f'SET "TEMP={TMPDIR}"\r\nSET "TMP={TMPDIR}"\r\n' if TMPDIR else ""
    bat.write_text(f'@ECHO OFF\r\n{tmp}CALL "{RUN_ASTER}" "{export}"\r\n', encoding="utf-8")
    return bat


if __name__ == "__main__":
    outdir, t_end, dt_arch = sys.argv[1], float(sys.argv[2]), float(sys.argv[3])
    for c in (sys.argv[4:] or CASES):
        print(make(c, outdir, t_end, dt_arch))
